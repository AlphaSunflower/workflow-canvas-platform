function applySql() {
  if (report.errors.length > 0 && !options.force) {
    console.error(`Refusing to apply migration because report has ${report.errors.length} errors. Use --force to override.`);
    process.exit(1);
  }

  const databaseUrl = options.databaseUrl ?? process.env.DATABASE_URL;
  const psql = options.psql ?? "psql";
  const args = [];

  if (databaseUrl) {
    args.push(databaseUrl);
  }

  args.push("-v", "ON_ERROR_STOP=1", "-f", sqlPath);

  const result = spawnSync(psql, args, {
    cwd: backendRoot,
    stdio: "inherit",
    shell: false,
  });

  if (result.error) {
    console.error(result.error);
  }

  if ((result.status ?? 1) !== 0) {
    process.exit(result.status ?? 1);
  }
}

