#!/usr/bin/env node
import { createHash } from "node:crypto";
import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const backendRoot = path.resolve(__dirname, "..");

const options = parseArgs(process.argv.slice(2));
const sourceRoot = path.resolve(options.sourceRoot ?? backendRoot);
const dataRoot = path.join(sourceRoot, "data");
const storageRoot = path.join(sourceRoot, "storage");
const label = sanitizeLabel(options.label ?? new Date().toISOString().replaceAll(":", "-"));
const migrationId = options.migrationId ?? deterministicUuid(`legacy_migration_run:${sourceRoot}:${label}`);
const outputDir = path.resolve(
  options.outputDir ?? path.join(backendRoot, ".tmp", "migrations", "json-store-to-db", label),
);
const sqlPath = path.join(outputDir, "migration.sql");
const reportPath = path.join(outputDir, "report.json");
const readmePath = path.join(outputDir, "README.md");

const report = {
  migrationId,
  label,
  sourceRoot,
  dataRoot,
  storageRoot,
  generatedAt: new Date().toISOString(),
  mode: options.apply ? "apply" : "dry-run",
  counts: {
    fileBlobs: 0,
    fileAssets: 0,
    fileBlobVariants: 0,
    fileUploads: 0,
    fileEvents: 0,
    storageObjects: 0,
    users: 0,
    refreshTokens: 0,
    auditLogs: 0,
    workflows: 0,
    workflowGroups: 0,
    workflowFileBindings: 0,
    executionRuns: 0,
    executionTasks: 0,
    taskEvents: 0,
    taskFileLinks: 0,
    intermediateArtifacts: 0,
  },
  warnings: [],
  errors: [],
  files: {},
};

const statements = [];
const knownFileIds = new Set();
const knownBlobIds = new Set();
const knownWorkflowIds = new Set();
const knownRunIds = new Set();
const knownTaskIds = new Set();
const storageObjectKeys = new Set();
const taskFileLinkKeys = new Set();
const placeholderFileIds = new Set();
const blobIdsBySha256 = new Map();

main();

function main() {
  mkdirSync(outputDir, { recursive: true });
  addHeader();

  migrateFilesStore();
  migrateStorageIndex();
  migrateAccountsStore();
  migrateWorkflowStores();
  migrateExecutionsStore();
  migrateIntermediateArtifactsStore();
  addMigrationRunRecord();
  addFooter();

  const sql = `${statements.join("\n\n")}\n`;
  writeFileSync(sqlPath, sql, "utf8");
  writeFileSync(reportPath, JSON.stringify(report, null, 2), "utf8");
  writeFileSync(readmePath, buildReadme(), "utf8");

  if (options.apply) {
    applySql();
  }

  printSummary();
}

function addHeader() {
  statements.push([
    "-- Generated by backend/scripts/migrate-json-store-to-db.mjs",
    `-- Migration id: ${migrationId}`,
    `-- Source root: ${sourceRoot}`,
    `-- Generated at: ${report.generatedAt}`,
    "begin;",
    "set constraints all deferred;",
  ].join("\n"));
}

function addFooter() {
  statements.push("commit;");
}

function migrateFilesStore() {
  const storePath = firstExistingPath([
    path.join(dataRoot, "files", "files-store.json"),
    path.join(dataRoot, "files-store.json"),
  ]);
  const store = readJsonOptional(storePath, { blobs: [], files: [], pendingUploads: [] });
  report.files.filesStore = storePath;

  const blobs = Array.isArray(store.blobs) ? store.blobs : [];
  const files = Array.isArray(store.files) ? store.files : [];
  const pendingUploads = Array.isArray(store.pendingUploads) ? store.pendingUploads : [];

  for (const blob of blobs) {
    const id = normalizeUuid(blob.id, "file_blobs.id");
    const sha256 = normalizeSha256(blob.sha256);
    const storageKey = normalizeNonEmptyString(blob.storageKey);

    if (!id || !sha256 || !storageKey) {
      report.errors.push({ type: "invalid_file_blob", blob });
      continue;
    }

    if (blobIdsBySha256.has(sha256) && blobIdsBySha256.get(sha256) !== id) {
      report.errors.push({
        type: "duplicate_file_blob_sha256",
        sha256,
        firstBlobId: blobIdsBySha256.get(sha256),
        duplicateBlobId: id,
      });
      continue;
    }

    blobIdsBySha256.set(sha256, id);
    knownBlobIds.add(id);
    report.counts.fileBlobs += 1;
    statements.push(insertOnConflictUpdate("file_blobs", {
      id,
      sha256,
      size: toInteger(blob.size, 0),
      mime_type: normalizeNonEmptyString(blob.mimeType) ?? "application/octet-stream",
      storage_key: storageKey,
      storage_provider: normalizeNonEmptyString(blob.storageProvider) ?? "local",
      extension: nullableString(blob.extension),
      width: nullableInteger(blob.width),
      height: nullableInteger(blob.height),
      preview_storage_key: nullableString(blob.previewStorageKey),
      preview_mime_type: nullableString(blob.previewMimeType),
      preview_size: nullableInteger(blob.previewSize),
      preview_width: nullableInteger(blob.previewWidth),
      preview_height: nullableInteger(blob.previewHeight),
      thumbnail_storage_key: nullableString(blob.thumbnailStorageKey),
      thumbnail_mime_type: nullableString(blob.thumbnailMimeType),
      thumbnail_size: nullableInteger(blob.thumbnailSize),
      thumbnail_width: nullableInteger(blob.thumbnailWidth),
      thumbnail_height: nullableInteger(blob.thumbnailHeight),
      duration: nullableNumber(blob.duration),
      created_at: normalizeTimestamp(blob.createdAt),
      updated_at: normalizeTimestamp(blob.createdAt),
    }, ["id"], [
      "sha256",
      "size",
      "mime_type",
      "storage_key",
      "storage_provider",
      "extension",
      "width",
      "height",
      "preview_storage_key",
      "preview_mime_type",
      "preview_size",
      "preview_width",
      "preview_height",
      "thumbnail_storage_key",
      "thumbnail_mime_type",
      "thumbnail_size",
      "thumbnail_width",
      "thumbnail_height",
      "duration",
      "updated_at",
    ]));

    insertFileBlobVariant({
      blobId: id,
      variant: "original",
      storageProvider: normalizeNonEmptyString(blob.storageProvider) ?? "local",
      storageKey,
      mimeType: normalizeNonEmptyString(blob.mimeType) ?? "application/octet-stream",
      size: toInteger(blob.size, 0),
      extension: nullableString(blob.extension),
      width: nullableInteger(blob.width),
      height: nullableInteger(blob.height),
      duration: nullableNumber(blob.duration),
      createdAt: normalizeTimestamp(blob.createdAt),
    });

    if (blob.previewStorageKey) {
      insertFileBlobVariant({
        blobId: id,
        variant: "preview",
        storageProvider: normalizeNonEmptyString(blob.storageProvider) ?? "local",
        storageKey: blob.previewStorageKey,
        mimeType: normalizeNonEmptyString(blob.previewMimeType) ?? "application/octet-stream",
        size: nullableInteger(blob.previewSize),
        extension: extensionFromStorageKey(blob.previewStorageKey),
        width: nullableInteger(blob.previewWidth),
        height: nullableInteger(blob.previewHeight),
        duration: null,
        createdAt: normalizeTimestamp(blob.createdAt),
      });
    }

    if (blob.thumbnailStorageKey) {
      insertFileBlobVariant({
        blobId: id,
        variant: "thumbnail",
        storageProvider: normalizeNonEmptyString(blob.storageProvider) ?? "local",
        storageKey: blob.thumbnailStorageKey,
        mimeType: normalizeNonEmptyString(blob.thumbnailMimeType) ?? "application/octet-stream",
        size: nullableInteger(blob.thumbnailSize),
        extension: extensionFromStorageKey(blob.thumbnailStorageKey),
        width: nullableInteger(blob.thumbnailWidth),
        height: nullableInteger(blob.thumbnailHeight),
        duration: null,
        createdAt: normalizeTimestamp(blob.createdAt),
      });
    }

    checkStorageFile(storageKey, "file_blob.original", id);
    checkStorageFile(blob.previewStorageKey, "file_blob.preview", id);
    checkStorageFile(blob.thumbnailStorageKey, "file_blob.thumbnail", id);
  }

  for (const file of files) {
    const id = normalizeUuid(file.id, "file_assets.id");
    if (!id) {
      report.errors.push({ type: "invalid_file_asset", file });
      continue;
    }

    const blobIdCandidate = nullableUuid(file.blobId, "file_assets.blob_id");
    const blobId = blobIdCandidate && knownBlobIds.has(blobIdCandidate)
      ? blobIdCandidate
      : null;
    if (blobId && !knownBlobIds.has(blobId)) {
      report.warnings.push({ type: "file_asset_missing_blob", fileId: id, blobId });
    }
    if (blobIdCandidate && !blobId) {
      report.warnings.push({
        type: "file_asset_missing_blob",
        fileId: id,
        blobId: blobIdCandidate,
        action: "blob_id_set_null",
      });
    }

    knownFileIds.add(id);
    report.counts.fileAssets += 1;
    statements.push(insertOnConflictUpdate("file_assets", {
      id,
      user_id: nullableString(file.userId),
      blob_id: blobId,
      original_name: normalizeNonEmptyString(file.originalName) ?? "unknown",
      display_name: normalizeNonEmptyString(file.displayName) ?? normalizeNonEmptyString(file.originalName) ?? "unknown",
      mime_type: normalizeNonEmptyString(file.mimeType) ?? "application/octet-stream",
      file_type: normalizeFileType(file.fileType),
      source_type: normalizeSourceType(file.sourceType),
      status: normalizeFileStatus(file.status),
      pending_upload_id: nullableUuid(file.pendingUploadId, "file_assets.pending_upload_id"),
      sha256: nullableString(file.sha256),
      size: nullableInteger(file.size),
      extension: nullableString(file.extension),
      width: nullableInteger(file.width),
      height: nullableInteger(file.height),
      duration: nullableNumber(file.duration),
      preview_ready: Boolean(file.previewReady),
      preview_width: nullableInteger(file.previewWidth),
      preview_height: nullableInteger(file.previewHeight),
      thumbnail_ready: Boolean(file.thumbnailReady),
      thumbnail_width: nullableInteger(file.thumbnailWidth),
      thumbnail_height: nullableInteger(file.thumbnailHeight),
      created_at: normalizeTimestamp(file.createdAt),
      updated_at: normalizeTimestamp(file.createdAt),
    }, ["id"], [
      "user_id",
      "blob_id",
      "original_name",
      "display_name",
      "mime_type",
      "file_type",
      "source_type",
      "status",
      "pending_upload_id",
      "sha256",
      "size",
      "extension",
      "width",
      "height",
      "duration",
      "preview_ready",
      "preview_width",
      "preview_height",
      "thumbnail_ready",
      "thumbnail_width",
      "thumbnail_height",
      "updated_at",
    ]));

    insertFileEvent({
      fileId: id,
      blobId,
      actorUserId: nullableString(file.userId),
      eventType: "legacy_file_asset_migrated",
      payload: {
        originalName: file.originalName,
        source: "files-store.json",
        status: file.status,
      },
      createdAt: normalizeTimestamp(file.createdAt),
    });
  }

  for (const pendingUpload of pendingUploads) {
    const uploadId = normalizeUuid(pendingUpload.uploadId, "file_uploads.id");
    const fileId = nullableUuid(pendingUpload.fileId, "file_uploads.file_id");

    if (!uploadId || !fileId) {
      report.errors.push({ type: "invalid_pending_upload", pendingUpload });
      continue;
    }

    if (!knownFileIds.has(fileId)) {
      report.warnings.push({ type: "pending_upload_missing_file_asset", uploadId, fileId });
    }

    report.counts.fileUploads += 1;
    statements.push(insertOnConflictUpdate("file_uploads", {
      id: uploadId,
      file_id: fileId,
      user_id: nullableString(pendingUpload.userId),
      sha256: normalizeSha256(pendingUpload.sha256) ?? "",
      size: toInteger(pendingUpload.size, 0),
      mime_type: normalizeNonEmptyString(pendingUpload.mimeType) ?? "application/octet-stream",
      original_name: normalizeNonEmptyString(pendingUpload.originalName) ?? "unknown",
      display_name: normalizeNonEmptyString(pendingUpload.displayName) ?? normalizeNonEmptyString(pendingUpload.originalName) ?? "unknown",
      file_type: normalizeFileType(pendingUpload.fileType),
      source_type: normalizeSourceType(pendingUpload.sourceType),
      width: nullableInteger(pendingUpload.width),
      height: nullableInteger(pendingUpload.height),
      duration: nullableNumber(pendingUpload.duration),
      status: "pending",
      created_at: normalizeTimestamp(pendingUpload.createdAt),
    }, ["id"], [
      "file_id",
      "user_id",
      "sha256",
      "size",
      "mime_type",
      "original_name",
      "display_name",
      "file_type",
      "source_type",
      "width",
      "height",
      "duration",
      "status",
    ]));
  }
}

