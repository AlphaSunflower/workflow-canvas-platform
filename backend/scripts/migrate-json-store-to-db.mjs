function migrateStorageIndex() {
  const storePath = path.join(dataRoot, "storage-index.json");
  const store = readJsonOptional(storePath, { files: [] });
  report.files.storageIndex = existsSync(storePath) ? storePath : null;

  const files = Array.isArray(store.files) ? store.files : [];

  for (const file of files) {
    const storageProvider = normalizeNonEmptyString(file.storageProvider) ?? "local";
    const storageKey = normalizeNonEmptyString(file.storageKey);
    const sha256 = normalizeSha256(file.sha256);

    if (!storageKey || !sha256) {
      report.errors.push({ type: "invalid_storage_object", file });
      continue;
    }

    const identityKey = `${storageProvider}:${storageKey}`;
    if (storageObjectKeys.has(identityKey)) {
      continue;
    }

    const legacyBlobId = nullableUuid(file.blobId, "storage_objects.legacy_blob_id");
    if (legacyBlobId && !knownBlobIds.has(legacyBlobId)) {
      report.warnings.push({
        type: "storage_object_missing_legacy_blob",
        storageKey,
        blobId: legacyBlobId,
        action: "legacy_blob_id_set_null",
      });
    }

    storageObjectKeys.add(identityKey);
    report.counts.storageObjects += 1;
    statements.push(insertOnConflictUpdate("storage_objects", {
      legacy_blob_id: legacyBlobId && knownBlobIds.has(legacyBlobId) ? legacyBlobId : null,
      sha256,
      file_type: normalizeFileType(file.fileType),
      source_type: normalizeSourceType(file.sourceType),
      original_name: normalizeNonEmptyString(file.originalName) ?? "unknown",
      mime_type: normalizeNonEmptyString(file.mimeType) ?? "application/octet-stream",
      storage_provider: storageProvider,
      storage_key: storageKey,
      absolute_path: nullableString(file.absolutePath),
      size: toInteger(file.size, 0),
      extension: nullableString(file.extension),
      width: nullableInteger(file.width),
      height: nullableInteger(file.height),
      created_at: normalizeTimestamp(file.createdAt),
      migrated_at: report.generatedAt,
    }, ["storage_provider", "storage_key"], [
      "legacy_blob_id",
      "sha256",
      "file_type",
      "source_type",
      "original_name",
      "mime_type",
      "absolute_path",
      "size",
      "extension",
      "width",
      "height",
      "migrated_at",
    ]));

    checkStorageFile(storageKey, "storage_index", file.blobId ?? storageKey);
  }
}

