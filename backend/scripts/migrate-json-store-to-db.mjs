function parseArgs(args) {
  const parsed = {
    apply: false,
    force: false,
  };

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];

    switch (arg) {
      case "--source-root":
        parsed.sourceRoot = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--output-dir":
        parsed.outputDir = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--label":
        parsed.label = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--migration-id":
        parsed.migrationId = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--database-url":
        parsed.databaseUrl = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--psql":
        parsed.psql = readArgValue(args, index, arg);
        index += 1;
        break;
      case "--apply":
        parsed.apply = true;
        break;
      case "--force":
        parsed.force = true;
        break;
      case "--help":
      case "-h":
        printHelp();
        process.exit(0);
        break;
      default:
        console.error(`Unknown option: ${arg}`);
        printHelp();
        process.exit(1);
    }
  }

  if (parsed.migrationId && !isUuid(parsed.migrationId)) {
    console.error("--migration-id must be a UUID.");
    process.exit(1);
  }

  return parsed;
}

function readArgValue(args, index, name) {
  const value = args[index + 1];
  if (!value || value.startsWith("--")) {
    console.error(`Missing value for ${name}.`);
    process.exit(1);
  }

  return value;
}

