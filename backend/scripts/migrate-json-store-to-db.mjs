function insertTaskFileLinksFromTask(task, storeTaskFileLinks) {
  const taskId = normalizeUuid(task.id, "task_file_links.task_id");
  if (!taskId) {
    return;
  }

  const workflowId = nullableString(task.workflowId);
  const groupId = normalizeNonEmptyString(task.groupId) ?? "default";
  const references = [];
  const storedTaskFileLinks = Array.isArray(storeTaskFileLinks)
    ? storeTaskFileLinks.filter((link) => link?.taskId === taskId)
    : [];
  if (Array.isArray(task.taskFileLinks)) {
    storedTaskFileLinks.push(...task.taskFileLinks);
  }

  for (const link of storedTaskFileLinks) {
    references.push({
      id: link.id,
      fileId: link.fileId,
      role: normalizeTaskFileRole(link.role),
      sourceHandle: link.sourceHandle,
      orderIndex: link.orderIndex,
      groupId: link.groupId,
      createdAt: link.createdAt,
    });
  }

  if (task.whiteModelFileId) {
    references.push({ fileId: task.whiteModelFileId, role: "input", sourceHandle: "whiteModelFileId" });
  }

  if (task.styleReferenceFileId) {
    references.push({ fileId: task.styleReferenceFileId, role: "reference", sourceHandle: "styleReferenceFileId" });
  }

  if (Array.isArray(task.input?.referenceFileIds)) {
    task.input.referenceFileIds.forEach((fileId, index) => {
      references.push({ fileId, role: "reference", sourceHandle: "input.referenceFileIds", orderIndex: index });
    });
  }

  if (Array.isArray(task.input?.fileIds)) {
    task.input.fileIds.forEach((fileId, index) => {
      references.push({ fileId, role: "input", sourceHandle: "input.fileIds", orderIndex: index });
    });
  }

  if (task.input?.sourceFileId) {
    references.push({ fileId: task.input.sourceFileId, role: "input", sourceHandle: "input.sourceFileId" });
  }

  if (task.input?.maskFileId) {
    references.push({ fileId: task.input.maskFileId, role: "reference", sourceHandle: "input.maskFileId" });
  }

  if (task.resultFileId) {
    references.push({ fileId: task.resultFileId, role: "output", sourceHandle: "resultFileId" });
  }

  for (const reference of references) {
    const fileId = normalizeUuid(reference.fileId, "task_file_links.file_id");
    if (!fileId) {
      continue;
    }

    if (!knownFileIds.has(fileId)) {
      report.warnings.push({
        type: "task_file_link_missing_file_asset",
        taskId,
        fileId,
        sourceHandle: reference.sourceHandle,
      });
      ensurePlaceholderFileAsset(fileId, {
        source: "task_file_link",
        taskId,
        workflowId,
        userId: task.userId,
      });
    }

    const role = normalizeTaskFileRole(reference.role);
    const sourceHandle = nullableString(reference.sourceHandle);
    const orderIndex = nullableInteger(reference.orderIndex);
    const key = `${taskId}:${fileId}:${role}:${sourceHandle ?? ""}:${orderIndex ?? ""}`;
    if (taskFileLinkKeys.has(key)) {
      continue;
    }

    taskFileLinkKeys.add(key);
    report.counts.taskFileLinks += 1;
    statements.push(insertOnConflictDoNothing("task_file_links", {
      id: nullableUuid(reference.id, "task_file_links.id") ?? deterministicUuid(`task_file_link:${key}`),
      task_id: taskId,
      file_id: fileId,
      workflow_id: workflowId,
      role,
      order_index: orderIndex,
      source_handle: sourceHandle,
      group_id: normalizeNonEmptyString(reference.groupId) ?? groupId,
      created_at: normalizeTimestamp(reference.createdAt ?? task.createdAt),
    }, ["id"]));
  }
}

function migrateWorkflowTaskEventStreams() {
  const workflowsDir = path.join(dataRoot, "workflows");
  if (!existsSync(workflowsDir)) {
    return;
  }

  for (const workflowName of readdirSync(workflowsDir)) {
    const eventsDir = path.join(workflowsDir, workflowName, "events");
    if (!existsSync(eventsDir) || !statSync(path.join(workflowsDir, workflowName)).isDirectory()) {
      continue;
    }

    const workflowId = normalizeUuid(workflowName, "task_events.workflow_id");
    if (!workflowId || !statSync(eventsDir).isDirectory()) {
      continue;
    }

    for (const entryName of readdirSync(eventsDir)) {
      if (!entryName.endsWith(".jsonl")) {
        continue;
      }

      const filePath = path.join(eventsDir, entryName);
      const lines = readFileSync(filePath, "utf8")
        .split(/\r?\n/u)
        .map((line) => line.trim())
        .filter(Boolean);

      for (const line of lines) {
        try {
          insertTaskEvent(JSON.parse(line), workflowId);
        } catch (error) {
          report.warnings.push({
            type: "invalid_task_event_jsonl_line",
            filePath,
            message: error instanceof Error ? error.message : String(error),
          });
        }
      }
    }
  }
}

